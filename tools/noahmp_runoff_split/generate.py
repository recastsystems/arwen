#!/usr/bin/env python3
"""Generate gpuwm/core/kernels/noahmp_water_split.cuh.

Separate surface / subsurface runoff options (opt_runsrf / opt_runsub),
re-implemented from published descriptions, not bitwise to upstream.

The split kernel is OUR OWN WRF-v4-lineage SOILWATER/WATER port
(noahmp_water_options.cuh, WRF public-domain notice) with every OPT_RUN gate
re-assigned to the surface or the subsurface half.  The assignment of each gate
follows the public Noah-MP v5.0 technical description (He et al. 2023,
NCAR/TN-575+STR, Sect. 3.7.8, Eqs. 3.7.198-3.7.338); no NCAR/noahmp, WRF 4.8
noahmp-submodule or other UCAR-licensed source was opened.  See
PROVENANCE-clean-runoff-split.md beside this script.

Every replacement below must hit exactly the stated number of times, so the
derived text cannot drift silently from the header it is cut from.  With
SRF == SUB every gate reduces to the original RUN gate, so the derived
column performs the same operations in the same order as the stock one.

    python -I tools/noahmp_runoff_split/generate.py           # write
    python -I tools/noahmp_runoff_split/generate.py --check   # verify
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "gpuwm/core/kernels/noahmp_water_options.cuh"
OUT = ROOT / "gpuwm/core/kernels/noahmp_water_split.cuh"


def cut(text, start, end):
    i = text.index(start)
    j = text.index(end, i)
    return text[i:j]


def sub(text, old, new, count=1):
    n = text.count(old)
    if n != count:
        raise SystemExit(f"expected {count} of {old!r}, found {n}")
    return text.replace(old, new)


def unassigned(text):
    return "RUN" in text.replace("RUNSRF", "").replace("RUNSUB", "").replace("OPT_RUN", "")


HEADER = """// GENERATED by tools/noahmp_runoff_split/generate.py -- do not edit.
// Separate surface and subsurface runoff options (opt_runsrf / opt_runsub).
// Re-implemented from published descriptions, not bitwise to upstream.
// Gates assigned per the public Noah-MP v5.0 technical description
// (He et al. 2023, NCAR/TN-575+STR, Sect. 3.7.8); arithmetic is our own
// WRF-v4-lineage port in noahmp_water_options.cuh (WRF public-domain notice,
// licenses/LICENSE-WRF-public-domain.txt). No NCAR/noahmp code was read.
// Appended only to the split module; the stock and selected images are
// compiled without it. NOAHMP_SPLIT_SRF / NOAHMP_SPLIT_SUB select the pair.
namespace noahmp_water_options {
// Parameter tail: the surface option's stock tail sits at offset 0 exactly as
// in the stock layout; a subsurface tail the surface tail does not already
// carry follows it (TOPMODEL: FSATMX, TIMEAN, PSISAT[4]; MMF: FSATMX, PSISAT[4]).
__host__ __device__ constexpr int split_surface_tail(int s) {
    return s==1||s==2 ? 6 : s==5 ? 5 : s==6||s==7 ? 8 : s==8 ? 3 : 0;
}
__host__ __device__ constexpr bool split_topo(int s, int b) { return s<=2 || b==1 || b==2; }
__host__ __device__ constexpr bool split_mmf(int s, int b) { return s==5 || b==5; }
__host__ __device__ constexpr int split_topo_off(int s) { return s<=2 ? 0 : split_surface_tail(s); }
__host__ __device__ constexpr int split_mmf_off(int s) { return s==5 ? 0 : split_surface_tail(s); }
__host__ __device__ constexpr int split_tail_width(int s, int b) {
    return split_surface_tail(s) + ((b==1||b==2) && s>2 ? 6 : 0) + (b==5 && s!=5 ? 5 : 0);
}

"""

ENTRY = """
#if defined(NOAHMP_SPLIT_SRF) && defined(NOAHMP_SPLIT_SUB)
extern "C" __global__ void k_water_split(const float *par,const float *fin,
    const int *iin,float *fout,int *iout,int n,int inf,int infdv,int soil_steps,int calculate_soil,int tdrn,int irrigation) {
    if(inf==1)noahmp_water_options::column_split<1,NOAHMP_SPLIT_SRF,NOAHMP_SPLIT_SUB>(par,fin,iin,fout,iout,n,infdv,soil_steps,calculate_soil,tdrn,irrigation,0);
    else noahmp_water_options::column_split<2,NOAHMP_SPLIT_SRF,NOAHMP_SPLIT_SUB>(par,fin,iin,fout,iout,n,infdv,soil_steps,calculate_soil,tdrn,irrigation,0);
}
#endif
"""


def derive(src):
    gw = cut(src, "__device__ void groundwater(const float *p", "// ZWTEQ:7587-7625")
    eq = cut(src, "__device__ void equilibrium_water_table(", "// Native COMPUTE_VIC_SURFRUNOFF")
    sw = cut(src, "template<int INF, int RUN, int WET=0>\n__device__ void d_soilwater(",
             "template<int INF, int RUN, int WET=0>\n__device__ void d_water(")
    # The snow compaction option's helpers (opt_snow_compact=2) sit between
    # d_soilwater and d_water in the stock header; the split module already
    # compiles that header, so they are not copied (a second copy would be a
    # duplicate definition).  column_split passes compaction through to the
    # stock helpers exactly as column does.
    marker = ("// " + "-" * 75 + "\n"
              "// Snow compaction option 2")
    if marker in sw:
        sw = sw[:sw.index(marker)]
    wa = cut(src, "template<int INF, int RUN, int WET=0>\n__device__ void d_water(",
             "template<int INF, int RUN, int WET=0>\n__device__ void column(")
    co = cut(src, "template<int INF, int RUN, int WET=0>\n__device__ void column(",
             "\n}\n\nextern \"C\" __global__ void k_water_selected(")

    # Niu et al. 2007 groundwater (tech note Sect. 3.7.8.5 item 4): the
    # subsurface tail is addressed through its own pointer, because on a
    # split it follows the surface tail instead of sharing offset 0 with it.
    gw = sub(gw, "__device__ void groundwater(const float *p,const float *z,float dt,",
             "__device__ void groundwater_split(const float *p,const float *pt,const float *z,float dt,")
    gw = sub(gw, "glibc_expf(-p[W_P_STRIDE+1])", "glibc_expf(-pt[1])")
    gw = sub(gw, "-p[W_P_STRIDE+2+iwt]", "-pt[2+iwt]")
    if "W_P_STRIDE" in gw:
        raise SystemExit("groundwater_split still reads the shared tail")
    # Equilibrium water table, Eqs. 3.7.322-3.7.327.
    eq = sub(eq, "__device__ void equilibrium_water_table(const float *p,const float *z,",
             "__device__ void equilibrium_water_table_split(const float *p,const float *pt,const float *z,")
    eq = sub(eq, "p[W_P_STRIDE+2]", "pt[2]")
    if "W_P_STRIDE" in eq:
        raise SystemExit("equilibrium_water_table_split still reads the shared tail")

    sw = sub(sw, "template<int INF, int RUN, int WET=0>\n__device__ void d_soilwater(",
             "template<int INF, int SRF, int SUB, int WET=0>\n__device__ void d_soilwater_split(")
    # The equilibrium water table serves the surface saturated fraction of
    # OptRunoffSurface=2 (Eq. 3.7.204) and the TOPMODEL baseflow of
    # OptRunoffSubsurface=2 (Eq. 3.7.328); the baseflow is subsurface only.
    sw = sub(sw, "    if (RUN == 2) {\n        equilibrium_water_table(par,zsoil,dz,sh2o,zwt);\n"
                 "        *runsub=FMUL(FMUL(FMUL(FSUB(K_ONE,fcrmax),4.0f),glibc_expf(-par[W_P_STRIDE+1])),"
                 "glibc_expf(FMUL(-2.0f,*zwt)));\n    }\n",
             "    if (SRF == 2 || SUB == 2)\n"
             "        equilibrium_water_table_split(par,par+W_P_STRIDE+split_topo_off(SRF),zsoil,dz,sh2o,zwt);\n"
             "    if (SUB == 2)\n"
             "        *runsub=FMUL(FMUL(FMUL(FSUB(K_ONE,fcrmax),4.0f),glibc_expf(-par[W_P_STRIDE+split_topo_off(SRF)+1])),"
             "glibc_expf(FMUL(-2.0f,*zwt)));\n")
    # Surface runoff and infiltration, Eqs. 3.7.198-3.7.236 (OptRunoffSurface).
    sw = sub(sw, "if (RUN == 1 || RUN == 2 || RUN==5) {", "if (SRF == 1 || SRF == 2 || SRF==5) {")
    sw = sub(sw, "float fff=RUN==1?", "float fff=SRF==1?")
    sw = sub(sw, "float fsat=RUN==5?", "float fsat=SRF==5?")
    sw = sub(sw, "    if (RUN == 3) {\n        d_infil(", "    if (SRF == 3) {\n        d_infil(")
    sw = sub(sw, "} else if (RUN == 4) {", "} else if (SRF == 4) {")
    sw = sub(sw, "if (RUN == 6) vic(", "if (SRF == 6) vic(")
    sw = sub(sw, "if (RUN == 7) xaj(", "if (SRF == 7) xaj(")
    sw = sub(sw, "if(RUN==8)dynamic_vic(", "if(SRF==8)dynamic_vic(")
    # Fine-step re-evaluation, Sect. 3.7.8.2 (1): OptRunoffSurface 3, 6, 7, 8.
    sw = sub(sw, "if (qinsur > K_ZERO && RUN == 3) {", "if (qinsur > K_ZERO && SRF == 3) {")
    sw = sub(sw, "if(qinsur>K_ZERO && RUN == 6)", "if(qinsur>K_ZERO && SRF == 6)")
    sw = sub(sw, "if(qinsur>K_ZERO && RUN == 7)", "if(qinsur>K_ZERO && SRF == 7)")
    sw = sub(sw, "if(qinsur>K_ZERO && RUN==8)", "if(qinsur>K_ZERO && SRF==8)")
    # Bottom drainage, Eq. 3.7.255 (keyed on OptRunoffSubsurface), and the
    # MMF bottom store, Eqs. 3.7.256-3.7.257.
    sw = sub(sw, "d_srt<INF,RUN>(", "d_srt<INF,SUB>(")
    # Wetland option (Zhang et al. 2022): its gates replace the surface
    # saturated fraction, so they key on the surface option.  k_water_split
    # never instantiates WET=1 (the host refuses wetland on a split pair).
    sw = sub(sw, "if (WET && RUN == 3) {", "if (WET && SRF == 3) {")
    sw = sub(sw, "(RUN == 1 || RUN == 2 || RUN == 3 || RUN == 5)", "(SRF == 1 || SRF == 2 || SRF == 3 || SRF == 5)")
    sw = sub(sw, "float wplus = RUN==5?d_sstep5(", "float wplus = SUB==5?d_sstep5(")
    # Tile drainage, Sect. 3.7.8.4: described for runoff option 3 only.  The
    # host refuses tile drainage on a split; here it needs both halves at 3.
    sw = sub(sw, "if(RUN==3 && tdrn==1", "if(SRF==3 && SUB==3 && tdrn==1")
    sw = sub(sw, "else if(RUN==3 && tdrn==2", "else if(SRF==3 && SUB==3 && tdrn==2")
    # Eqs. 3.7.329-3.7.330 (SUB=2 removal) and 3.7.331-3.7.337 (SUB/=1 floor,
    # taken from the deep recharge for SUB=5, Eq. 3.7.336).
    sw = sub(sw, "    if (RUN == 2) {\n        float total=K_ZERO;", "    if (SUB == 2) {\n        float total=K_ZERO;")
    sw = sub(sw, "    if (RUN != 1) {\n", "    if (SUB != 1) {\n")
    sw = sub(sw, "if(RUN==5)*deeprech=", "if(SUB==5)*deeprech=")
    if unassigned(sw):
        raise SystemExit("d_soilwater_split still has an unassigned RUN gate")

    wa = sub(wa, "template<int INF, int RUN, int WET=0>\n__device__ void d_water(",
             "template<int INF, int SRF, int SUB, int WET=0>\n__device__ void d_water_split(")
    wa = sub(wa, "d_soilwater<INF,RUN,WET>(", "d_soilwater_split<INF,SRF,SUB,WET>(")
    # Subsurface runoff, Sect. 3.7.8.5: 1 groundwater, 3/4/6/7/8 drainage
    # (Eq. 3.7.338), 5 MMF shallow water table.
    wa = sub(wa, "        if (RUN == 1) {\n            float qin,qdis;\n            groundwater(par,",
             "        if (SUB == 1) {\n            float qin,qdis;\n"
             "            groundwater_split(par,par+W_P_STRIDE+split_topo_off(SRF),")
    wa = sub(wa, "if(RUN==3 || RUN==4 || RUN==6 || RUN==7 || RUN==8)",
             "if(SUB==3 || SUB==4 || SUB==6 || SUB==7 || SUB==8)")
    wa = sub(wa, "        if(RUN==5) {\n            groundwater_shallowwatertable(par+P_SMCMAX,par+W_P_STRIDE+1,",
             "        if(SUB==5) {\n"
             "            groundwater_shallowwatertable(par+P_SMCMAX,par+W_P_STRIDE+split_mmf_off(SRF)+1,")
    if unassigned(wa):
        raise SystemExit("d_water_split still has an unassigned RUN gate")

    co = sub(co, "template<int INF, int RUN, int WET=0>\n__device__ void column(",
             "template<int INF, int SRF, int SUB, int WET=0>\n__device__ void column_split(")
    co = sub(co, "    int base_tail=RUN==5?5:RUN==8?3:RUN>=6?8:RUN<=2?6:0;\n"
                 "    int in_gw=RUN==5?9:RUN<=2?3:0,out_gw=RUN==5?5:RUN<=2?3:0;\n",
             "    int base_tail=split_tail_width(SRF,SUB);\n"
             "    int in_gw=split_mmf(SRF,SUB)?9:split_topo(SRF,SUB)?3:0,"
             "out_gw=split_mmf(SRF,SUB)?5:split_topo(SRF,SUB)?3:0;\n")
    co = sub(co, "    if(RUN==5){zwt=x[W_IN_STRIDE];", "    if(split_mmf(SRF,SUB)){zwt=x[W_IN_STRIDE];")
    co = sub(co, "    if(RUN<=2) {zwt=x[W_IN_STRIDE];", "    if(split_topo(SRF,SUB)) {zwt=x[W_IN_STRIDE];")
    co = sub(co, "if(tdrn && RUN>2)zwt=tx[2];", "if(tdrn && !split_topo(SRF,SUB))zwt=tx[2];")
    co = sub(co, "d_water<INF,RUN,WET>(", "d_water_split<INF,SRF,SUB,WET>(")
    co = sub(co, "(WET?(RUN==3?2:1):0)", "(WET?(SRF==3?2:1):0)")
    co = sub(co, "(WET && RUN==3)?", "(WET && SRF==3)?")
    co = sub(co, "RUN==5?x+W_IN_STRIDE+5:nullptr", "split_mmf(SRF,SUB)?x+W_IN_STRIDE+5:nullptr")
    co = sub(co, "    if(RUN==5){q[W_OUT_STRIDE]=zwt;", "    if(split_mmf(SRF,SUB)){q[W_OUT_STRIDE]=zwt;")
    co = sub(co, "    if(RUN<=2) {q[W_OUT_STRIDE]=zwt;", "    if(split_topo(SRF,SUB)) {q[W_OUT_STRIDE]=zwt;")
    if unassigned(co):
        raise SystemExit("column_split still has an unassigned RUN gate")

    return HEADER + gw + "\n" + eq + "\n" + sw + "\n" + wa + "\n" + co + "\n}\n" + ENTRY


def main():
    body = derive(SRC.read_text(encoding="ascii"))
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        if OUT.read_text(encoding="ascii") != body:
            raise SystemExit(f"{OUT} is stale; rerun {Path(__file__).name}")
        return
    OUT.write_bytes(body.encode("ascii"))


if __name__ == "__main__":
    main()
